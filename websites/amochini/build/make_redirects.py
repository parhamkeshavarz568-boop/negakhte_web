#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Turn a list of old WordPress URLs into exact 301 rules for .htaccess.

    python3 build/make_redirects.py old-urls.txt

`old-urls.txt` is one URL (or path) per line — see docs/MIGRATION.md for the
three ways to get it out of WordPress.

Matching is done on the NORMALISED Persian text of the old slug against the
normalised text of every new product, so it survives percent-encoding,
Arabic-vs-Persian character drift, ZWNJ inconsistency and Persian digits.
Anything it cannot match with confidence is listed for a human to map by hand
rather than being silently pointed at the wrong product.
"""
import json, os, re, sys, urllib.parse, difflib, collections

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from normalize import fold, ZWNJ, BRANDS, CATEGORIES

CAT_HINTS = {
    "brake-pads": ["لنت", "lent", "tormoz", "pad"],
    "brake-discs": ["دیسک", "disk", "disc", "charkh", "rotor"],
    "brake-drums": ["کاسه", "kase", "drum"],
}
AXLE_HINTS = {"front": ["جلو", "jelo", "front"], "rear": ["عقب", "aghab", "rear"]}


def key(s):
    """Normalised comparison key: percent-decoded, folded, ZWNJ->space,
    punctuation flattened, digits Latin."""
    s = urllib.parse.unquote(s)
    s = fold(s).replace(ZWNJ, " ")
    s = re.sub(r"[^\w؀-ۿ]+", " ", s)
    return re.sub(r"\s+", " ", s).strip().lower()


def tokens(s):
    return [t for t in key(s).split() if t not in ("و", "the", "for")]


def score(old_tokens, prod):
    """Token overlap plus category/axle/model agreement."""
    hay = set(tokens(prod["title"]) + tokens(prod["search"]) + tokens(prod["sku"]))
    hit = sum(1 for t in old_tokens if t in hay)
    s = hit / max(len(old_tokens), 1) * 100
    joined = " ".join(old_tokens)
    for cat, hints in CAT_HINTS.items():
        if any(h in joined for h in hints):
            s += 25 if prod["category"] == cat else -35
    for ax, hints in AXLE_HINTS.items():
        if any(re.search(rf"\b{h}\b", joined) for h in hints):
            s += 20 if prod["axle"] == ax else -25
    if prod["model"]:
        mk = key(prod["model"])
        if mk and mk in joined:
            s += 30
    if "tra x" in joined or "trax" in joined:
        s += 15 if prod["variant"] == "tra-x" else -10
    elif prod["variant"] == "tra-x":
        s -= 10
    return s


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        print("ERROR: pass the path to your exported URL list.")
        return 1
    src = sys.argv[1]
    products = json.load(open(os.path.join(HERE, "data", "products.json"),
                              encoding="utf-8"))

    lines = [l.strip() for l in open(src, encoding="utf-8") if l.strip()
             and not l.startswith("#")]
    rules, unmatched, skipped = [], [], []
    seen = set()

    for raw in lines:
        path = urllib.parse.urlparse(raw).path if "://" in raw else raw
        path = path.strip()
        if not path.startswith("/"):
            path = "/" + path
        if path in seen:
            continue
        seen.add(path)

        # structural URLs are already handled by the static rules in .htaccess
        STRUCTURAL = (r"^(wp-|feed/?$|comments/|author/|\d{4}/|product-category/|"
                      r"product-tag/|shop/?$|cart/|checkout/|my-account/|xmlrpc)")
        if path == "/" or re.match(STRUCTURAL, path.lstrip("/"), re.I):
            skipped.append((path, "handled by structural rule"))
            continue

        slug = path.rstrip("/").split("/")[-1]
        tk = tokens(slug)
        if not tk:
            skipped.append((path, "empty slug"))
            continue

        ranked = sorted(products, key=lambda p: -score(tk, p))
        best, second = ranked[0], ranked[1] if len(ranked) > 1 else None
        bs = score(tk, best)
        ss = score(tk, second) if second else -999

        # Confident only when the winner is clearly ahead of the runner-up.
        if bs >= 60 and (bs - ss) >= 12:
            rules.append((path, best["url"], round(bs), best["sku"], best["title"]))
        else:
            cands = [(round(score(tk, p)), p["url"], p["title"]) for p in ranked[:3]]
            unmatched.append((path, cands))

    out = []
    out.append("  # --- exact product redirects, generated by make_redirects.py ---")
    out.append("  # NOTE: mod_rewrite matches RewriteRule against the PERCENT-DECODED")
    out.append("  # URL path, so Persian slugs appear here as literal UTF-8, not %XX.")
    out.append("  # This file must stay UTF-8 encoded.")
    for old, new, sc, sku, title in sorted(rules):
        decoded = urllib.parse.unquote(old).strip("/")
        esc = re.escape(decoded).replace(r"\/", "/")
        out.append(f"  # {title}  ({sku}, confidence {sc})")
        out.append(f"  RewriteRule ^{esc}/?$ {new} [R=301,L]")
        if decoded != old.strip("/"):
            # Belt and braces: some LiteSpeed/Apache setups hand the encoded
            # form through. THE_REQUEST is always the raw request line.
            enc = re.escape(old.strip("/"))
            out.append(f"  RewriteCond %{{THE_REQUEST}} \\s/+{enc}[/?\\s]")
            out.append(f"  RewriteRule ^ {new} [R=301,L]")
    body = "\n".join(out)

    dest = os.path.join(HERE, "data", "redirects.generated.conf")
    open(dest, "w", encoding="utf-8").write(body + "\n")

    print(f"read      {len(lines)} URLs")
    print(f"matched   {len(rules)}  -> {dest}")
    print(f"skipped   {len(skipped)} (already covered by structural rules)")
    print(f"UNMATCHED {len(unmatched)} — map these by hand:\n")
    for path, cands in unmatched:
        print(f"  {path}")
        for sc, u, t in cands:
            print(f"        {sc:4d}  {u}   {t}")
    if unmatched:
        print("\nAdd hand-written rules to build/data/redirects.manual.conf")
        print("in the same RewriteRule format; build.py concatenates both.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
